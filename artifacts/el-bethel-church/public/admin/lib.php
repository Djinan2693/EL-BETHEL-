function require_csrf() {
    $sent = $_SERVER['HTTP_X_CSRF_TOKEN'] ?? '';
    if (!is_string($sent) || !hash_equals($_SESSION['csrf'] ?? '', $sent)) fail('Security check failed. Please reload the page.', 403);
    // Extra guard: if the browser says where the request came from, it must be us.
    $origin = $_SERVER['HTTP_ORIGIN'] ?? '';
    if ($origin !== '') {
        $host = parse_url($origin, PHP_URL_HOST);
        if (!$host || strcasecmp($host, explode(':', $_SERVER['HTTP_HOST'] ?? '')[0]) !== 0) fail('Security check failed.', 403);
    }
}

function client_key() { return hash('sha256', ($_SERVER['REMOTE_ADDR'] ?? 'unknown') . '|eb'); }

function read_attempts() {
    $all = is_file(ATTEMPTS_FILE) ? json_decode((string)@file_get_contents(ATTEMPTS_FILE), true) : [];
    if (!is_array($all)) $all = [];
    $now = time();
    foreach ($all as $k => $list) {
        $all[$k] = array_values(array_filter((array)$list, function ($t) use ($now) { return $now - (int)$t < LOGIN_WINDOW; }));
        if (!$all[$k]) unset($all[$k]);
    }
    return $all;
}

function login_locked() {
    $all = read_attempts();
    return count($all[client_key()] ?? []) >= LOGIN_MAX_FAILS;
}

function record_failed_login() {
    $all = read_attempts();
    $all[client_key()][] = time();
    @file_put_contents(ATTEMPTS_FILE, json_encode($all), LOCK_EX);
}

function clear_failed_logins() {
    $all = read_attempts();
    unset($all[client_key()]);
    @file_put_contents(ATTEMPTS_FILE, json_encode($all), LOCK_EX);
}

/* ── Content: read / validate / write ────────────────────────────────────── */
function read_json_file($path) {
    if (!is_file($path)) return null;
    $data = json_decode((string)file_get_contents($path), true);
    return is_array($data) ? $data : null;
}

function clean_text($v, $max) {
    if (!is_string($v)) return '';
    $v = trim(strip_tags($v));
    $v = preg_replace('/[\x00-\x08\x0B\x0C\x0E-\x1F\x7F]/u', '', $v);
    return function_exists('mb_substr') ? mb_substr($v, 0, $max) : substr($v, 0, $max);
}

/** "/contact" or "https://…" only — anything else (javascript:, //evil…) is dropped. */
function clean_link($v) {
    $v = clean_text($v, 500);
    if ($v === '') return '';
    if (preg_match('~^/(?!/)[A-Za-z0-9/_\-.?=&%#]*$~', $v)) return $v;
    if (preg_match('#^https?://[^\s<>"]+$#i', $v)) return $v;
    return '';
}

/** Built-in image file name, or a file we uploaded ourselves. */
function clean_image($v) {
    $v = is_string($v) ? trim($v) : '';
    if (preg_match('#^[A-Za-z0-9._\-]+\.(jpe?g|png|webp)$#i', $v)) return $v;
    if (preg_match('#^/content/uploads/[A-Za-z0-9_\-]+\.(jpe?g|png)$#', $v) && is_file(SITE_ROOT . $v)) return $v;
    return '';
}

function clean_images($list, $max, $min = 1) {
    $out = [];
    foreach ((array)$list as $item) {
        if (!is_array($item)) continue;
        $src = clean_image($item['src'] ?? '');
        if ($src === '') continue;
        $out[] = ['src' => $src, 'alt' => clean_text($item['alt'] ?? '', 160)];
        if (count($out) >= $max) break;
    }
    if (count($out) < $min) fail('Please keep at least ' . $min . ' photo' . ($min > 1 ? 's' : '') . ' in this section.');
    return $out;
}

/** Whitelist every field: only these keys, these types, these lengths. */
function sanitize_content($in) {
    if (!is_array($in)) fail('Nothing to save.');
    $t = (array)($in['ticker'] ?? []);
    $h = (array)($in['home'] ?? []);
    $a = (array)($in['announcement'] ?? []);
    $c = (array)($in['church'] ?? []);

    $items = [];
    foreach ((array)($t['items'] ?? []) as $it) {
        $text = clean_text(is_array($it) ? ($it['text'] ?? '') : '', 200);
        if ($text === '') continue;
        $row = ['text' => $text];
        $link = clean_link($it['link'] ?? '');
        if ($link !== '') $row['link'] = $link;
        $items[] = $row;
        if (count($items) >= 12) break;
    }

    $stats = [];
    foreach (array_slice((array)($h['stats'] ?? []), 0, 4) as $s) {
        if (!is_array($s)) continue;
        $stats[] = ['value' => clean_text($s['value'] ?? '', 12), 'label' => clean_text($s['label'] ?? '', 40)];
    }

    $ctaLabel = clean_text($a['cta']['label'] ?? '', 40);
    $ctaHref  = clean_link($a['cta']['href'] ?? '');
    $popup = [
        'id'               => preg_replace('/[^A-Za-z0-9_\-]/', '', (string)($a['id'] ?? 'popup')) ?: 'popup',
        'enabled'          => !empty($a['enabled']),
        'delayMs'          => 900,
        'showOnceForHours' => in_array((int)($a['showOnceForHours'] ?? 72), [0, 24, 72, 168], true) ? (int)$a['showOnceForHours'] : 72,
        'badge'            => clean_text($a['badge'] ?? '', 40),
        'title'            => clean_text($a['title'] ?? '', 120),
        'description'      => clean_text($a['description'] ?? '', 600),
        'date'             => clean_text($a['date'] ?? '', 80),
        'time'             => clean_text($a['time'] ?? '', 80),
        'location'         => clean_text($a['location'] ?? '', 200),
        'image'            => clean_image($a['image'] ?? ''),
    ];
    if ($ctaLabel !== '' && $ctaHref !== '') $popup['cta'] = ['label' => $ctaLabel, 'href' => $ctaHref];
    if ($popup['enabled'] && $popup['title'] === '') fail('The popup needs a title (or switch the popup off).');

    $email = clean_text($c['email'] ?? '', 120);
    if ($email !== '' && !filter_var($email, FILTER_VALIDATE_EMAIL)) fail('The email address does not look right: ' . $email);

    $storyImage = clean_image($h['storyImage'] ?? '');

    return [
        'ticker' => [
            'enabled' => !empty($t['enabled']) && count($items) > 0,
            'speed'   => in_array($t['speed'] ?? '', ['slow', 'normal', 'fast'], true) ? $t['speed'] : 'normal',
            'items'   => $items,
        ],
        'home' => [
            'heroTitleLine1' => clean_text($h['heroTitleLine1'] ?? '', 60),
            'heroTitleLine2' => clean_text($h['heroTitleLine2'] ?? '', 60),
            'heroSubtitle'   => clean_text($h['heroSubtitle'] ?? '', 300),
            'heroSlides'     => clean_images($h['heroSlides'] ?? [], 8, 1),
            'stats'          => $stats,
            'storyTitle'     => clean_text($h['storyTitle'] ?? '', 80),
            'storyImage'     => $storyImage !== '' ? $storyImage : 'about-community.jpg',
            'galleryTitle'   => clean_text($h['galleryTitle'] ?? '', 80),
            'gallery'        => clean_images($h['gallery'] ?? [], 40, 1),
        ],
        'announcement' => $popup,
        'church' => [
            'phone'   => clean_text($c['phone'] ?? '', 40),
            'email'   => $email,
            'address' => clean_text($c['address'] ?? '', 300),
        ],
    ];
}

function write_atomic($path, $string) {
    $tmp = $path . '.tmp-' . bin2hex(random_bytes(4));
    if (@file_put_contents($tmp, $string, LOCK_EX) === false) return false;
    @chmod($tmp, 0644);
    return @rename($tmp, $path);
}

function backup_current($reason) {
    $source = CONTENT_FILE;
    if (!is_file($source)) {
        // First publish ever: keep the original website so it can be restored.
        if (!is_file(DEFAULTS_FILE)) return;
        $source = DEFAULTS_FILE;
        $reason = 'original';
    }
    $name = date('Ymd-His') . '-' . preg_replace('/[^a-z]/', '', $reason) . '.json';
    @copy($source, BACKUP_DIR . '/' . $name);
    $files = glob(BACKUP_DIR . '/*.json') ?: [];
    rsort($files);
    foreach (array_slice($files, MAX_BACKUPS) as $old) @unlink($old);
}

function save_content($clean, $reason = 'save') {
    $clean['updatedAt'] = date('c');
    $clean['updatedBy'] = $_SESSION['user'] ?? '';
    backup_current($reason);
    $json = json_encode($clean, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
    if (!write_atomic(CONTENT_FILE, $json)) fail('The server could not save the changes. Please contact ' . SUPPORT_NAME . '.', 500);
    return $clean;
}

/* ── Image upload ────────────────────────────────────────────────────────── */
function handle_upload($file) {
    if (!is_array($file) || ($file['error'] ?? UPLOAD_ERR_NO_FILE) !== UPLOAD_ERR_OK) {
        $err = $file['error'] ?? UPLOAD_ERR_NO_FILE;
        if ($err === UPLOAD_ERR_INI_SIZE || $err === UPLOAD_ERR_FORM_SIZE) fail('This photo is too large for the server.');
        fail('The photo did not arrive. Please try again.');
    }
    if ($file['size'] > MAX_UPLOAD_BYTES) fail('This photo is too large (max 12 MB).');
    if (!is_uploaded_file($file['tmp_name'])) fail('Upload rejected.');

    $info = @getimagesize($file['tmp_name']);
    if (!$info || !in_array($info[2], [IMAGETYPE_JPEG, IMAGETYPE_PNG, IMAGETYPE_WEBP], true)) fail('Please choose a JPG, PNG or WebP photo.');

    $name = date('Ymd') . '-' . bin2hex(random_bytes(6));
    $isPng = $info[2] === IMAGETYPE_PNG;

    if (function_exists('imagecreatefromstring')) {
        // Re-draw the picture: this removes anything hidden inside the file
        // and shrinks phone photos to a sensible size.
        $img = @imagecreatefromstring((string)file_get_contents($file['tmp_name']));
        if (!$img) fail('This photo could not be read. Please try another one.');
        $w = imagesx($img); $h = imagesy($img);
        $scale = min(1, MAX_IMAGE_SIDE / max($w, $h));
        if ($scale < 1) {
            $nw = (int)round($w * $scale); $nh = (int)round($h * $scale);
            $dst = imagecreatetruecolor($nw, $nh);
            if ($isPng) { imagealphablending($dst, false); imagesavealpha($dst, true); }
            imagecopyresampled($dst, $img, 0, 0, 0, 0, $nw, $nh, $w, $h);
            imagedestroy($img);
            $img = $dst;
        }
        $path = UPLOAD_DIR . '/' . $name . ($isPng ? '.png' : '.jpg');
        $ok = $isPng ? imagepng($img, $path, 7) : imagejpeg($img, $path, 84);
        imagedestroy($img);
        if (!$ok) fail('The server could not save this photo.', 500);
    } else {
        if ($info[2] === IMAGETYPE_WEBP) fail('Please choose a JPG or PNG photo.');
        $path = UPLOAD_DIR . '/' . $name . ($isPng ? '.png' : '.jpg');
        if (!move_uploaded_file($file['tmp_name'], $path)) fail('The server could not save this photo.', 500);
    }
    @chmod($path, 0644);
    return '/content/uploads/' . basename($path);
}
